    speed: float = 0.00278         # m/s
    weld_length: float = 0.100     # m; bead length (plate length remains 150 mm)
    x_start: float = 0.025         # m; 25 mm unwelded margin at start
    y_track: float = 0.040         # m; specimen centreline
