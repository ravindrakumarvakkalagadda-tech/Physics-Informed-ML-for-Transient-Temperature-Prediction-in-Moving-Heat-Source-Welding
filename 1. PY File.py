def material_properties(T_C):
   
    k = np.interp(T_C, MAT_T, K_TABLE)
    alpha = np.interp(T_C, MAT_T, ALPHA_TABLE)
    cp = np.interp(T_C, MAT_T, CP_TABLE)
    rho = np.interp(T_C, MAT_T, RHO_TABLE)
    return k, cp, alpha, rho


def material_table_diagnostics():
    """Return the supplied properties."""
    rho_from_identity = K_TABLE / (ALPHA_TABLE * CP_TABLE)
    return pd.DataFrame({
        "temperature_C": MAT_T,
        "k_W_mK": K_TABLE,
        "alpha_m2_s": ALPHA_TABLE,
        "cp_J_kgK": CP_TABLE,
        "density_supplied_kg_m3": RHO_TABLE,
        "density_from_k_alpha_cp_kg_m3": rho_from_identity,
        "density_difference_kg_m3": RHO_TABLE - rho_from_identity,
    })


def make_grid(cfg):
    nx = int(round(cfg.Lx / cfg.dx))
    ny = int(round(cfg.Ly / cfg.dy))
    nz = int(round(cfg.Lz / cfg.dz))
    dx, dy, dz = cfg.Lx/nx, cfg.Ly/ny, cfg.Lz/nz
    x = (np.arange(nx) + 0.5) * dx
    y = (np.arange(ny) + 0.5) * dy
    z = (np.arange(nz) + 0.5) * dz
    X, Y, Z = np.meshgrid(x, y, z, indexing="ij")
    return x, y, z, X, Y, Z, dx, dy, dz


def goldak_source(X, Y, Z, t, cfg):
    """
    Goldak double ellipsoid, volumetric source W/m3.
    x-axis is the travel direction; source moves in +x.
    Front is ahead of torch (xi >= 0), rear is behind torch (xi < 0).
    The discrete source is renormalised so sum(q*cell_volume) = eta*V*I.
    """
    power = cfg.efficiency * cfg.voltage * cfg.current
    xs = cfg.x_start + cfg.speed * t
    xi = X - xs
    eta_y = Y - cfg.y_track

    q = np.zeros_like(X)
    front = xi >= 0.0
    rear = ~front

    # Goldak Gaussian shape factors. The factors ff/fr describe the
    # relative front/rear distribution. Discrete normalisation below
    # guarantees the specified total net power in this finite domain.
    pref_f = 6.0*np.sqrt(3.0)*cfg.ff*power / (
        np.pi**1.5 * cfg.af * cfg.b * cfg.c
    )
    pref_r = 6.0*np.sqrt(3.0)*cfg.fr*power / (
        np.pi**1.5 * cfg.ar * cfg.b * cfg.c
    )

    q[front] = pref_f * np.exp(
        -3.0*(xi[front]**2/cfg.af**2
              + eta_y[front]**2/cfg.b**2
              + Z[front]**2/cfg.c**2)
    )
    q[rear] = pref_r * np.exp(
        -3.0*(xi[rear]**2/cfg.ar**2
              + eta_y[rear]**2/cfg.b**2
              + Z[rear]**2/cfg.c**2)
    )

    # Numerical energy normalisation: prevents finite-grid truncation or
    # front/rear convention ambiguity from changing total applied power.
    cell_volume = (cfg.Lx / X.shape[0]) * (cfg.Ly / X.shape[1]) * (cfg.Lz / X.shape[2])
    integrated = np.sum(q) * cell_volume
    if integrated > 0:
        q *= power / integrated
    return q, xs, power


def uniform_surface_source(X, Y, Z, t, cfg, dx, dy, dz):
    """Apply a moving uniform heat flux to the top surface using exact overlap areas.

    Returns a volumetric-equivalent source (W/m3) in the first layer of cells.
    For each top-face cell, the heat deposited is q_flux * overlap_area.
    Dividing that power by the cell volume gives the source term used in the
    cell-centred energy equation. The sum over all cells is exactly eta*V*I
    whenever the complete footprint lies inside the plate.
    """
    power = cfg.efficiency * cfg.voltage * cfg.current  # W entering the plate
    xs = cfg.x_start + cfg.speed * t

    # Fixed nominal footprint and flux; efficiency is applied exactly once.
    footprint_area = cfg.footprint_length * cfg.footprint_width
    q_flux = power / footprint_area  # W/m2

    # Cell-face edges in the x-y plane. x and y are cell-centre coordinates.
    x_centres = X[:, 0, 0]
    y_centres = Y[0, :, 0]
    x_left = x_centres - dx/2.0
    x_right = x_centres + dx/2.0
    y_left = y_centres - dy/2.0
    y_right = y_centres + dy/2.0

    # Moving rectangular footprint boundaries.
    src_x_left = xs - cfg.footprint_length/2.0
    src_x_right = xs + cfg.footprint_length/2.0
    src_y_left = cfg.y_track - cfg.footprint_width/2.0
    src_y_right = cfg.y_track + cfg.footprint_width/2.0

    # Exact geometric overlap of each surface cell with the source rectangle.
    overlap_x = np.maximum(
        0.0, np.minimum(x_right, src_x_right) - np.maximum(x_left, src_x_left)
    )
    overlap_y = np.maximum(
        0.0, np.minimum(y_right, src_y_right) - np.maximum(y_left, src_y_left)
    )
    overlap_area = overlap_x[:, None] * overlap_y[None, :]

    covered_area = float(np.sum(overlap_area))
    if covered_area <= 0.0:
        raise RuntimeError("Moving heat-source footprint does not overlap the plate surface.")

    # Do not silently renormalise a truncated footprint at a plate edge.
    # The selected weld path should keep the full footprint inside the domain.
    area_tolerance = max(1e-12, footprint_area*1e-9)
    if abs(covered_area - footprint_area) > area_tolerance:
        raise RuntimeError(
            f"Heat-source footprint is partly outside the plate: "
            f"covered area={covered_area:.8e} m2, nominal area={footprint_area:.8e} m2. "
            "Check x_start, y_track, weld path and specimen dimensions."
        )

    qvol = np.zeros_like(X)
    # q_flux*overlap_area is power into each top-face cell (W).
    # Divide by dx*dy*dz to obtain W/m3 in the top boundary cell.
    qvol[:, :, 0] = q_flux * overlap_area / (dx*dy*dz)

    # Numerical power check: sum(qvol*cell_volume) must equal eta*V*I.
    applied_power = float(np.sum(qvol[:, :, 0]) * dx*dy*dz)
    if not np.isclose(applied_power, power, rtol=1e-10, atol=1e-8):
        raise RuntimeError(
            f"Heat-input check failed: applied {applied_power:.8f} W, expected {power:.8f} W."
        )

    n_cells = int(np.count_nonzero(overlap_area))
    return qvol, xs, power, q_flux, covered_area, n_cells


def source_field(X, Y, Z, t, cfg, dx, dy, dz):
    """Return volumetric-equivalent source field and diagnostic metadata."""
    if cfg.source_model == "uniform_surface":
        q, xs, power, q_flux, area, n_cells = uniform_surface_source(
            X, Y, Z, t, cfg, dx, dy, dz
        )
        return q, xs, power, {
            "surface_flux_W_m2": q_flux,
            "covered_footprint_area_m2": area,
            "nominal_footprint_area_m2": cfg.footprint_length*cfg.footprint_width,
            "footprint_cells": n_cells
        }
    elif cfg.source_model == "goldak":
        q, xs, power = goldak_source(X, Y, Z, t, cfg)
        return q, xs, power, {
            "surface_flux_W_m2": None,
            "discrete_footprint_area_m2": None,
            "footprint_cells": None
        }
    else:
        raise ValueError("source_model must be 'uniform_surface' or 'goldak'.")


def conductive_divergence(T, k, dx, dy, dz):
    """Compute div(k grad T) with harmonic face conductivity and zero conductive flux at outer faces."""
    nx, ny, nz = T.shape
    div = np.zeros_like(T)

    # x-direction internal faces
    kf = 2*k[1:,:,:]*k[:-1,:,:] / (k[1:,:,:] + k[:-1,:,:] + 1e-30)
    gx = kf * (T[1:,:,:] - T[:-1,:,:]) / dx
    div[:-1,:,:] += gx/dx
    div[1:,:,:] -= gx/dx

    # y-direction
    kf = 2*k[:,1:,:]*k[:,:-1,:] / (k[:,1:,:] + k[:,:-1,:] + 1e-30)
    gy = kf * (T[:,1:,:] - T[:,:-1,:]) / dy
    div[:,:-1,:] += gy/dy
    div[:,1:,:] -= gy/dy

    # z-direction
    kf = 2*k[:,:,1:]*k[:,:,:-1] / (k[:,:,1:] + k[:,:,:-1] + 1e-30)
    gz = kf * (T[:,:,1:] - T[:,:,:-1]) / dz
    div[:,:,:-1] += gz/dz
    div[:,:,1:] -= gz/dz

    return div


def boundary_loss(T, k, cfg, dx, dy, dz):
    """Boundary heat losses as W/m3 in boundary cells.

    Exposed top and side faces use convection + radiation. The bottom face
    uses conduction through the half-cell in series with the plate/table
    contact resistance. This gives a face heat flux and face temperature
    consistent with the cell-centred finite-volume representation.
    """
    TinfK = cfg.T_ambient_C + 273.15
    TK = np.maximum(T + 273.15, 1.0)
    loss = np.zeros_like(T)

    # Top face: convection + radiation to ambient.
    qtop = (cfg.h_convection*(T[:, :, 0] - cfg.T_ambient_C)
            + cfg.emissivity*cfg.sigma*(TK[:, :, 0]**4 - TinfK**4))
    loss[:, :, 0] += qtop/dz

    # Bottom face: half-cell conduction resistance + contact resistance.
    # q = (T_cell - T_table) / (dz/(2*k) + 1/h_contact)
    k_bottom = np.maximum(k[:, :, -1], 1.0e-12)
    h_eff = 1.0 / (1.0/cfg.h_contact + dz/(2.0*k_bottom))
    q_contact = h_eff*(T[:, :, -1] - cfg.T_table_C)
    loss[:, :, -1] += q_contact/dz

    # Four side faces: convection + radiation to ambient.
    qx0 = (cfg.h_convection*(T[0, :, :] - cfg.T_ambient_C)
           + cfg.emissivity*cfg.sigma*(TK[0, :, :]**4 - TinfK**4))
    qx1 = (cfg.h_convection*(T[-1, :, :] - cfg.T_ambient_C)
           + cfg.emissivity*cfg.sigma*(TK[-1, :, :]**4 - TinfK**4))
    loss[0, :, :] += qx0/dx
    loss[-1, :, :] += qx1/dx

    qy0 = (cfg.h_convection*(T[:, 0, :] - cfg.T_ambient_C)
           + cfg.emissivity*cfg.sigma*(TK[:, 0, :]**4 - TinfK**4))
    qy1 = (cfg.h_convection*(T[:, -1, :] - cfg.T_ambient_C)
           + cfg.emissivity*cfg.sigma*(TK[:, -1, :]**4 - TinfK**4))
    loss[:, 0, :] += qy0/dy
    loss[:, -1, :] += qy1/dy
    return loss


def reconstruct_backside_face_temperature(T, k, cfg, dz):
    """Reconstruct the physical bottom-face temperature from the last cell.

    The bottom face is at z=Lz. The last cell centre is dz/2 above it.
    The reconstruction satisfies the same series-resistance contact model
    used in boundary_loss().
    """
    T_cell = T[:, :, -1]
    k_cell = np.maximum(k[:, :, -1], 1.0e-12)
    h_eff = 1.0 / (1.0/cfg.h_contact + dz/(2.0*k_cell))
    q_contact = h_eff*(T_cell - cfg.T_table_C)
    T_face = T_cell - q_contact*dz/(2.0*k_cell)
    return T_face


def sample_bilinear_xy(field, x, y, x_query, y_query):
    """Bilinearly sample a cell-centred x-y field at an in-domain location."""
    i0, i1, fx = _linear_bracket(x, x_query)
    j0, j1, fy = _linear_bracket(y, y_query)
    v00 = field[i0, j0]
    v10 = field[i1, j0]
    v01 = field[i0, j1]
    v11 = field[i1, j1]
    return float((1-fx)*(1-fy)*v00 + fx*(1-fy)*v10
                 + (1-fx)*fy*v01 + fx*fy*v11)


def stable_timestep(cfg, dx, dy, dz, X, Y, Z):
    """Conservative explicit diffusion limit and source-heating limit.

    The source limit is calculated from the DISCRETELY NORMALISED Goldak field,
    not the unnormalised analytical peak. This matters when the source is
    truncated by the finite computational domain.
    """
    # Conservative bounds based on the tabulated temperature-dependent properties.
    alpha_max = float(np.max(ALPHA_TABLE))
    volumetric_heat_capacity_min = float(np.min(RHO_TABLE * CP_TABLE))
    dt_diff = 0.35 / (2.0*alpha_max*(1/dx**2 + 1/dy**2 + 1/dz**2))
    q0, _, _, _ = source_field(X, Y, Z, 0.0, cfg, dx, dy, dz)
    q_peak_discrete = float(np.max(q0))
    dt_source = cfg.max_temperature_rise_per_step * volumetric_heat_capacity_min / q_peak_discrete
    return min(cfg.dt_requested, dt_diff, dt_source), dt_diff, dt_source


def _linear_bracket(grid, value):
    """Return indices and interpolation fraction for a monotonic 1-D grid."""
    if value < grid[0] or value > grid[-1]:
        raise ValueError(f"Probe coordinate {value} lies outside grid [{grid[0]}, {grid[-1]}].")
    hi = int(np.searchsorted(grid, value, side="left"))
    if hi == 0:
        return 0, 0, 0.0
    if hi >= len(grid):
        return len(grid)-1, len(grid)-1, 0.0
    lo = hi - 1
    frac = (value - grid[lo]) / (grid[hi] - grid[lo])
    return lo, hi, float(frac)


def sample_temperature_trilinear(T, x, y, z, x_query, y_query, z_query):
    """Trilinearly interpolate T at an exact physical (x,y,z) coordinate."""
    i0, i1, fx = _linear_bracket(x, x_query)
    j0, j1, fy = _linear_bracket(y, y_query)
    k0, k1, fz = _linear_bracket(z, z_query)

    c000 = T[i0, j0, k0]
    c100 = T[i1, j0, k0]
    c010 = T[i0, j1, k0]
    c110 = T[i1, j1, k0]
    c001 = T[i0, j0, k1]
    c101 = T[i1, j0, k1]
    c011 = T[i0, j1, k1]
    c111 = T[i1, j1, k1]

    c00 = c000*(1-fx) + c100*fx
    c10 = c010*(1-fx) + c110*fx
    c01 = c001*(1-fx) + c101*fx
    c11 = c011*(1-fx) + c111*fx
    c0 = c00*(1-fy) + c10*fy
    c1 = c01*(1-fy) + c11*fy
    return float(c0*(1-fz) + c1*fz)


def verify_interpolation_implementation():
    """Unit test: trilinear interpolation must reproduce a linear 3-D field."""
    xt = np.array([0.0, 1.0, 2.0])
    yt = np.array([0.0, 1.0, 2.0])
    zt = np.array([0.0, 1.0, 2.0])
    XX, YY, ZZ = np.meshgrid(xt, yt, zt, indexing="ij")
    test_field = 100.0 + 2.0*XX + 5.0*YY + 7.0*ZZ
    got = sample_temperature_trilinear(test_field, xt, yt, zt, 0.4, 0.8, 1.2)
    expected = 100.0 + 2.0*0.4 + 5.0*0.8 + 7.0*1.2
    if not np.isclose(got, expected, rtol=0.0, atol=1e-10):
        raise RuntimeError(f"Interpolation unit test failed: got {got}, expected {expected}")
    return True


def run_simulation(cfg=CFG):
    out = Path(cfg.output_dir)
    out.mkdir(parents=True, exist_ok=True)

    verify_interpolation_implementation()
    x, y, z, X, Y, Z, dx, dy, dz = make_grid(cfg)
    T = np.full(X.shape, cfg.T_ambient_C, dtype=np.float64)
    dt, dt_diff, dt_source = stable_timestep(cfg, dx, dy, dz, X, Y, Z)

    # The 150 mm plate has a 100 mm bead, beginning 25 mm from its end.
    # Therefore the bead ends at x = 125 mm, leaving a 25 mm end margin.
    weld_end_x = cfg.x_start + cfg.weld_length
    if cfg.x_start < 0 or weld_end_x > cfg.Lx:
        raise ValueError('Weld path must lie completely within the plate domain.')
    calculated_weld_time = cfg.weld_length / cfg.speed
    t_end = calculated_weld_time
    nsteps = int(np.ceil(t_end/dt))
    save_every = max(1, int(round(cfg.output_interval/dt)))

    # Probe locations: exact physical coordinates, sampled at several depths.
    # z=1.0 and 3.75 mm are subsurface planes; z=z[-1] is the rear-adjacent
    # cell-centre plane (not the exact geometric back surface at 7.5 mm).
    offsets_mm = np.array([0,1,2,3,5,7,8,10], dtype=float)
    probe_x_m = cfg.x_start + 0.066
    probe_y_m = cfg.y_track + offsets_mm/1000.0
    probe_depths_mm = [1.0, 3.75, float(z[-1]*1000.0), cfg.Lz*1000.0]
    probe_depths_m = [v/1000.0 for v in probe_depths_mm]

    probe_records = []
    snapshots = []
    energy_records = []
    cumulative_input_J = 0.0
    cumulative_boundary_loss_J = 0.0
    cumulative_storage_change_J = 0.0

    cell_vol = dx*dy*dz
    t = 0.0
    for step in range(nsteps + 1):
        if step % save_every == 0 or step == nsteps:
            for depth_mm, depth_m in zip(probe_depths_mm, probe_depths_m):
                for off, yq in zip(offsets_mm, probe_y_m):
                    if np.isclose(depth_mm, cfg.Lz*1000.0):
                        k_now, _, _, _ = material_properties(T)
                        T_back_face = reconstruct_backside_face_temperature(T, k_now, cfg, dz)
                        temp_probe = sample_bilinear_xy(
                            T_back_face, x, y, probe_x_m, float(yq)
                        )
                    else:
                        temp_probe = sample_temperature_trilinear(
                            T, x, y, z, probe_x_m, float(yq), float(depth_m)
                        )
                    probe_records.append([t, off, depth_mm, temp_probe])
            snapshots.append((t, T[:, :, 0].copy()))  # top-surface plane
            energy_residual_J = cumulative_storage_change_J - (
                cumulative_input_J - cumulative_boundary_loss_J
            )
            energy_records.append([
                t, float(T.max()), float(T.mean()),
                cumulative_input_J, cumulative_boundary_loss_J,
                cumulative_storage_change_J, energy_residual_J
            ])

        if step == nsteps:
            break

        k, cp, alpha, rho = material_properties(T)
        qvol, xs, net_power, source_info = source_field(
            X, Y, Z, t, cfg, dx, dy, dz
        )
        div_cond = conductive_divergence(T, k, dx, dy, dz)
        qloss = boundary_loss(T, k, cfg, dx, dy, dz)

        dTdt = (div_cond + qvol - qloss) / (rho*cp)
        T_new = T + dt*dTdt

        # Global discrete energy accounting. The conduction operator uses
        # conservative internal face fluxes and zero conductive flux at the
        # outer faces, so its domain-integrated contribution should cancel.
        applied_power_W = float(np.sum(qvol) * cell_vol)
        boundary_loss_W = float(np.sum(qloss) * cell_vol)
        storage_increment_J = float(np.sum(rho*cp*(T_new - T)) * cell_vol)
        cumulative_input_J += applied_power_W * dt
        cumulative_boundary_loss_J += boundary_loss_W * dt
        cumulative_storage_change_J += storage_increment_J
        T = T_new
        t += dt

        if not np.isfinite(T).all():
            raise FloatingPointError("Non-finite temperature detected. Reduce timestep or inspect inputs.")

    probes = pd.DataFrame(
        probe_records,
        columns=["time_s", "distance_from_weld_line_mm", "probe_depth_mm", "temperature_C"]
    )
