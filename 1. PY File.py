"""
A Physics-Informed Machine Learning Framework for Predicting Transient Temperature Distribution in Moving Heat Source Welding Processes
Reference: 1. Rocha, E. J. F., Antonino, T. de S., Guimarães, P. B., Ferreira, R. A. S., Barbosa, J. M. A., & Rohatgi, J. (2018). Modeling of the temperature field generated by the deposition of weld bead on a steel butt joint by FEM techniques and thermographic images. Materials Research, 21(3), e20160796. https://doi.org/10.1590/1980-5373-MR-2016-0796)

Method:
- Cell-centred explicit finite-volume Method conduction solver.
- Moving Goldak double-ellipsoidal volumetric heat source and optional uniform surface-flux comparison model.
- linear temperature-dependent thermal properties k(T), alpha(T), cp(T), and supplied rho(T).
- Material-properties obtained fromt he reference in the range of 0-650 C;
- Radiation related information extracted from the manuscript.
- The bottom face is in full contact with a steel support table and uses a contact-conductance boundary condition.

"""

